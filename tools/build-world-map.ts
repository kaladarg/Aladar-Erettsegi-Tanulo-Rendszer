/**
 * Generates the world base map for the földrajz place cards and the map quiz from
 * Natural Earth 1:110m data (public domain, via the world-atlas package and the
 * Natural Earth repository): land, country borders, lakes and rivers.
 *
 *   npm run map:build:world
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { createRequire } from 'node:module';
import { feature, mesh } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { projectWorld } from '../src/content/cards/worldProjection';

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'),
) as Topology<{ countries: GeometryCollection; land: GeometryCollection }>;

type Ring = [number, number][];
const MIN_STEP = 0.6;

function pathOf(lines: Ring[], close: boolean): string {
  let d = '';
  for (const line of lines) {
    const points: [number, number][] = [];
    for (const [lon, lat] of line) {
      const [x, y] = projectWorld(lon, Math.max(-58, Math.min(84, lat)));
      const last = points.at(-1);
      // A jump across the date line starts a new piece instead of a line over the map.
      if (last && Math.abs(x - last[0]) > 500) {
        if (points.length >= 2)
          d += `M${points.map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L')}`;
        points.length = 0;
      } else if (last && Math.hypot(x - last[0], y - last[1]) < MIN_STEP) continue;
      points.push([x, y]);
    }
    if (points.length < (close ? 3 : 2)) continue;
    d += `M${points.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}${close ? 'Z' : ''}`;
  }
  return d;
}

const polygons = (g: GeoJSON.Geometry): Ring[] =>
  g.type === 'Polygon'
    ? (g.coordinates as Ring[])
    : g.type === 'MultiPolygon'
      ? (g.coordinates.flat() as Ring[])
      : [];

const land = feature(topology, topology.objects.land);
const landRings = ('features' in land ? land.features : [land]).flatMap((f) =>
  polygons(f.geometry),
);
const borders = mesh(topology, topology.objects.countries, (a, b) => a !== b);
const borderLines = (borders.type === 'MultiLineString' ? borders.coordinates : []) as Ring[];

async function naturalEarth(name: string): Promise<GeoJSON.FeatureCollection> {
  const cache = `node_modules/.cache/natural-earth/${name}.geojson`;
  if (!existsSync(cache)) {
    const url = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/${name}.geojson`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    mkdirSync(dirname(cache), { recursive: true });
    writeFileSync(cache, await response.text());
  }
  return JSON.parse(readFileSync(cache, 'utf8')) as GeoJSON.FeatureCollection;
}

const lakes = (await naturalEarth('ne_110m_lakes')).features.flatMap((f) => polygons(f.geometry));
const rivers = (await naturalEarth('ne_110m_rivers_lake_centerlines')).features.flatMap((f) =>
  f.geometry.type === 'LineString'
    ? [f.geometry.coordinates as Ring]
    : f.geometry.type === 'MultiLineString'
      ? (f.geometry.coordinates as Ring[])
      : [],
);

const out = `// Generated by tools/build-world-map.ts from Natural Earth 1:110m data (public domain). Do not edit.
export const LAND_PATH =
  '${pathOf(landRings, true)}';
export const BORDER_PATH =
  '${pathOf(borderLines, false)}';
export const RIVER_PATH =
  '${pathOf(rivers, false)}';
export const LAKE_PATH =
  '${pathOf(lakes, true)}';
`;
writeFileSync('src/content/cards/worldPaths.ts', out);
console.log(`world map: ${(out.length / 1024).toFixed(0)} kB`);
