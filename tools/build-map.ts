/**
 * Generates the base map for the history place cards from Natural Earth data
 * (public domain, via the world-atlas package): land and country borders of
 * Europe, the Mediterranean and the Near East in a Mercator projection.
 *
 *   npm run map:build
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { createRequire } from 'node:module';
import { feature, mesh } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { MAP_BOUNDS, project } from '../src/content/cards/projection';

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'),
) as Topology<{ countries: GeometryCollection; land: GeometryCollection }>;

type Ring = [number, number][];
const MIN_STEP = 0.45;
const [west, south, east, north] = MAP_BOUNDS;
const margin = 3;
const inside = ([lon, lat]: [number, number]) =>
  lon >= west - margin && lon <= east + margin && lat >= south - margin && lat <= north + margin;

/** Projects and thins a line; parts outside the area are dropped. */
function pathOf(lines: Ring[], close: boolean): string {
  let d = '';
  for (const line of lines) {
    if (!line.some(inside)) continue;
    const points: [number, number][] = [];
    let wasOutside = false;
    for (const point of line) {
      const out = !inside(point);
      const [x, y] = project(
        Math.max(west - margin, Math.min(east + margin, point[0])),
        Math.max(south - margin, Math.min(north + margin, point[1])),
      );
      const last = points.at(-1);
      const before = points.at(-2);
      // Runs outside the area are clamped onto its edge; points in a row on
      // the same edge line collapse into one segment.
      if (
        out &&
        wasOutside &&
        last &&
        before &&
        ((before[0] === last[0] && last[0] === x) || (before[1] === last[1] && last[1] === y))
      ) {
        points[points.length - 1] = [x, y];
        continue;
      }
      wasOutside = out;
      if (last && Math.hypot(x - last[0], y - last[1]) < MIN_STEP) continue;
      points.push([x, y]);
    }
    if (points.length < (close ? 3 : 2)) continue;
    d += `M${points.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}${close ? 'Z' : ''}`;
  }
  return d;
}

const land = feature(topology, topology.objects.land);
const landRings: Ring[] = [];
for (const f of 'features' in land ? land.features : [land]) {
  const g = f.geometry;
  if (g.type === 'Polygon') landRings.push(...(g.coordinates as Ring[]));
  if (g.type === 'MultiPolygon') for (const p of g.coordinates) landRings.push(...(p as Ring[]));
}
const borders = mesh(topology, topology.objects.countries, (a, b) => a !== b);
const borderLines = (borders.type === 'MultiLineString' ? borders.coordinates : []) as Ring[];

/** Natural Earth rivers and lakes, downloaded once and cached. */
async function naturalEarth(name: string): Promise<GeoJSON.FeatureCollection> {
  const cache = `node_modules/.cache/natural-earth/${name}.geojson`;
  if (!existsSync(cache)) {
    const url = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/${name}.geojson`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    mkdirSync(dirname(cache), { recursive: true });
    writeFileSync(cache, await response.text());
  }
  return JSON.parse(readFileSync(cache, 'utf8')) as GeoJSON.FeatureCollection;
}

const linesOf = (collection: GeoJSON.FeatureCollection, polygons: boolean): Ring[] =>
  collection.features.flatMap((f) => {
    const g = f.geometry;
    if (!polygons && g.type === 'LineString') return [g.coordinates as Ring];
    if (!polygons && g.type === 'MultiLineString') return g.coordinates as Ring[];
    if (polygons && g.type === 'Polygon') return g.coordinates as Ring[];
    if (polygons && g.type === 'MultiPolygon') return g.coordinates.flat() as Ring[];
    return [];
  });

const rivers = linesOf(await naturalEarth('ne_50m_rivers_lake_centerlines'), false);
const lakes = linesOf(await naturalEarth('ne_50m_lakes'), true);

const out = `// Generated by tools/build-map.ts from Natural Earth 1:50m data (public domain). Do not edit.
export const LAND_PATH =
  '${pathOf(landRings, true)}';
export const BORDER_PATH =
  '${pathOf(borderLines, false)}';
export const RIVER_PATH =
  '${pathOf(rivers, false)}';
export const LAKE_PATH =
  '${pathOf(lakes, true)}';
`;
writeFileSync('src/content/cards/mapPaths.ts', out);
console.log(`map: ${(out.length / 1024).toFixed(0)} kB`);
