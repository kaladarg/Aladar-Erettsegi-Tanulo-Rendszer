/**
 * Scaffolds a content repository next to the code repository.
 *   npm run content:init -- --dir ../erettsegi-gyakorlo-content
 */
import { access, mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { DEFAULT_LEVELS, DEFAULT_SUBJECTS } from '../src/content/catalog';
import { parseArgs, stringArg } from './lib/args';
import { isMain } from './lib/isMain';

const README = `# Érettségi Gyakorló content (private)

Official érettségi papers, marking schemes and the structured exam data
extracted from them, for the [Érettségi Gyakorló](https://github.com/kaladarg/Aladar-Erettsegi-Tanulo-Rendszer) app.

**Keep this repository private.** The papers belong to the Oktatási Hivatal and
contain third-party works. Do not publish until reuse has been cleared (see
CONTENT_NOTICE.md).

## Layout

\`\`\`
pack.json                     pack metadata (subjects, levels, notice)
manifest.json                 generated by "npm run content:pack"
exams/<exam-id>/source/       official PDFs + sources.json (from the crawler)
exams/<exam-id>/exam.json     extracted, reviewed exam data
reports/<exam-id>.md          review reports
\`\`\`

## Workflow (run from the code repository)

\`\`\`bash
npm run content:crawl   -- --out ../erettsegi-gyakorlo-content --from 2024
npm run content:extract -- --dir ../erettsegi-gyakorlo-content --exam matematika-kozep-2024-majus
npm run content:review  -- --dir ../erettsegi-gyakorlo-content
npm run content:pack    -- --dir ../erettsegi-gyakorlo-content
npm run dev:content     # the app loads this pack
\`\`\`
`;

const NOTICE = `# Content notice

The exam papers, attachments and javítási-értékelési útmutatók in \`exams/*/source/\`
are published by the Oktatási Hivatal (https://www.oktatas.hu) and belong to it;
many contain works of third parties. They are stored here for private
development and review only and are not licensed for redistribution.

The structured data in \`exam.json\` files is derived from these materials.
`;

export async function initContentRepo(dir: string): Promise<string[]> {
  const created: string[] = [];
  const write = async (name: string, content: string) => {
    const path = join(dir, name);
    try {
      await access(path);
    } catch {
      await writeFile(path, content);
      created.push(name);
    }
  };
  await mkdir(join(dir, 'exams'), { recursive: true });
  await mkdir(join(dir, 'reports'), { recursive: true });
  await write(
    'pack.json',
    `${JSON.stringify(
      {
        packId: 'oh-kozepszint',
        title: 'Középszintű érettségi feladatsorok',
        notice:
          'A feladatsorok és javítási-értékelési útmutatók az Oktatási Hivatal tulajdonát képezik.',
        repositoryUrl: 'https://github.com/kaladarg/erettsegi-gyakorlo-content',
        subjects: DEFAULT_SUBJECTS,
        levels: DEFAULT_LEVELS,
      },
      null,
      2,
    )}\n`,
  );
  await write('README.md', README);
  await write('CONTENT_NOTICE.md', NOTICE);
  await write('.gitattributes', '* text=auto eol=lf\n*.pdf binary\n*.zip binary\n*.mp3 binary\n');
  await write('.gitignore', '.DS_Store\n');
  await write('exams/.gitkeep', '');
  await write('reports/.gitkeep', '');
  return created;
}

if (isMain(import.meta.url)) {
  const dir = resolve(
    stringArg(parseArgs(process.argv.slice(2)), 'dir', '../erettsegi-gyakorlo-content'),
  );
  const created = await initContentRepo(dir);
  console.log(
    created.length
      ? `Created in ${dir}:\n  ${created.join('\n  ')}`
      : `${dir} is already initialized.`,
  );
}
